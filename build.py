#!/usr/bin/env python3
"""Build: issues.json -> issues.js (for the rack) + issue-N/index.html (static, shareable pages)."""
import json, html, os, urllib.parse
BASE = "https://hatlem72-creator.github.io/ace/"
SERIES = "Ace Is Back! True Tales"
I = json.load(open("issues.json"))
open("issues.js", "w").write("/* generated by build.py from issues.json, do not edit */\nconst ISSUES = " + json.dumps(I, ensure_ascii=False) + ";\n")
e = lambda s: html.escape(str(s), quote=True)
out = [x for x in I if x["status"] == "out"]

def meter(n):
    segs = "".join(f'<i class="{"on" if k < n else ""}" style="--k:{k}"></i>' for k in range(10))
    return f'<div class="meter" role="img" aria-label="Shock-o-meter: {n} out of 10"><span class="m-lbl">Shock-o-meter</span><span class="m-bar">{segs}</span><b>{n}/10</b></div>'

def share(url, text):
    u, t = urllib.parse.quote(url, safe=""), urllib.parse.quote(text, safe="")
    links = [("Facebook", f"https://www.facebook.com/sharer/sharer.php?u={u}", "fb"),
             ("X", f"https://twitter.com/intent/tweet?url={u}&text={t}", "x"),
             ("Reddit", f"https://www.reddit.com/submit?url={u}&title={t}", "rd"),
             ("WhatsApp", f"https://wa.me/?text={t}%20{u}", "wa")]
    a = "".join(f'<a class="badge {c}" href="{h}" target="_blank" rel="noopener">{n}</a>' for n, h, c in links)
    return f'<div class="share"><span class="sh-lbl">Share this issue!</span>{a}<button class="badge cp" type="button" data-url="{e(url)}">Copy link</button></div>'

for x in out:
    n = x["no"]; d = f"issue-{n}"; os.makedirs(d, exist_ok=True)
    url = f"{BASE}{d}/"; title = f'{x["seo"]} — {SERIES}'; img = BASE + x["share"]
    nxt = next((y for y in I if y["no"] == n + 1), None)
    tl = "".join(f'<a class="tl{" cur" if y["no"]==n else ""}" href="../issue-{y["no"]}/"><b>#{y["no"]}</b><span>{y["year"]}</span></a>' if y["status"]=="out" else f'<a class="tl soon" href="../#rack"><b>#{y["no"]}</b><span>Soon</span></a>' for y in I)
    body = "".join(f"<p>{p}</p>" for p in x["body"])
    quotes = "".join(f'<figure class="quote"><blockquote>“{e(q["text"])}”</blockquote><figcaption>— <a href="{e(q["href"])}" target="_blank" rel="noopener">{e(q["who"])}</a></figcaption></figure>' for q in x["quotes"])
    facts = "".join(f"<li><span>{e(k)}</span><b>{e(v)}</b></li>" for k, v in x["facts"])
    srcs = "".join(f'<li><a href="{e(h)}" target="_blank" rel="noopener">{e(t)}</a></li>' for t, h in x["sources"])
    legend = '<span class="legend-tag">Legend</span>' if x.get("legend") else '<span class="true-tag">100% True</span>'
    teaser = (f'<a class="teaser" href="../issue-{n+1}/"><span class="burst">Next issue</span><b>Issue #{n+1}: {e(nxt["title"])}</b><small>{e(nxt["kicker"])}</small></a>' if nxt and nxt["status"] == "out"
              else f'<a class="teaser" href="../#rack"><span class="burst">Next issue</span><b>Issue #{n+1}: coming soon!</b><small>Same Spaceman, new mayhem. Check back soon.</small></a>')
    page = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(title)}</title>
<meta name="description" content="{e(x["desc"])}">
<link rel="canonical" href="{url}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="{e(SERIES)}">
<meta property="og:title" content="{e(title)}">
<meta property="og:description" content="{e(x["desc"])}">
<meta property="og:url" content="{url}">
<meta property="og:image" content="{img}">
<meta property="og:image:width" content="1200"><meta property="og:image:height" content="630">
<meta property="og:image:alt" content="{e(x["title"])}: pop-art comic cover art from {e(SERIES)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{e(title)}">
<meta name="twitter:description" content="{e(x["desc"])}">
<meta name="twitter:image" content="{img}">
<link rel="icon" href="data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><text y='.9em' font-size='90'>⚡</text></svg>">
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Bangers&family=Comic+Neue:wght@400;700&family=Permanent+Marker&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../style.css">
<script type="application/ld+json">{json.dumps({"@context":"https://schema.org","@type":"Article","headline":x["seo"],"description":x["desc"],"image":img,"url":url,"isPartOf":{"@type":"CreativeWorkSeries","name":SERIES},"about":{"@type":"Person","name":"Ace Frehley"}})}</script>
</head>
<body class="issue-page">
<canvas id="stars" aria-hidden="true"></canvas>
<header class="topbar"><a class="logo small" href="../"><span class="l1">Ace Is Back!</span> <span class="l2">True Tales</span></a><a class="back" href="../#rack">← Back to the rack</a></header>
<nav class="timeline" aria-label="Issues timeline"><span class="tl-label">Issues:</span><div class="tl-track">{tl}</div></nav>
<main class="issue">
  <div class="masthead"><span class="mh-series">Ace Is Back! True Tales</span><span class="mh-no">No. {n}</span><span class="mh-price">{e(x["price"])}</span></div>
  <h1 class="i-title">{e(x["title"])}</h1>
  <p class="kicker">{e(x["kicker"])}</p>
  <div class="i-meta"><span class="yr">{e(x["date"])}</span><span>{e(x["place"])}</span>{legend}</div>
  <figure class="strip"><picture><source srcset="../{x["strip"]}.webp" type="image/webp"><img src="../{x["strip"]}.jpg" alt="{e(x["stripAlt"])}" width="1200" height="675" onerror="this.closest('figure').classList.add('noimg')"></picture></figure>
  {meter(x["shock"])}
  <div class="i-grid">
    <article class="tale"><h2 class="cap">The true tale</h2>{body}<p class="note">{e(x.get("note",""))}</p></article>
    <aside class="side"><h2 class="cap">Fact file</h2><ul class="facts">{facts}</ul>{quotes}</aside>
  </div>
  <section class="sources"><h2 class="cap">Sources</h2><ol>{srcs}</ol></section>
  {share(url, x["seo"] + " — a true tale in comic form")}
  {teaser}
  <section class="poll-mount" id="vote"></section>
</main>
<footer class="foot"><div class="foot-in"><p>A non-commercial fan tribute to Ace Frehley (1951–2025). Not affiliated with KISS, the Frehley estate or any label. Original illustrations of scenes and objects only: no likenesses, makeup designs or logos.</p><p class="visits" id="visits" hidden>⚡ Readers since October 2026: <b id="visitCount"></b></p></div></footer>
<script src="../issues.js"></script>
<script src="../app.js"></script>
</body>
</html>
'''
    open(f"{d}/index.html", "w").write(page)
    print("built", d)
